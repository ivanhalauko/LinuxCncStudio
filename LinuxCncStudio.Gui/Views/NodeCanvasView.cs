using Avalonia;
using Avalonia.Controls;
using Avalonia.Media;
using Avalonia.Input;
using System;
using System.Collections.Generic;
using LinuxCncStudio.Core.Nodes;

namespace LinuxCncStudio.Gui.Views;

// Модифицированный холст с поддержкой интерактивного Drag-and-Drop и текстовых подписей
public class HalVisualCanvas : Control
{
    private List<BaseNode> _nodes = new List<BaseNode>();
    private BaseNode? _draggedNode = null;
    private Point _pointerOffset;

    public HalVisualCanvas()
    {
        // Инициализируем базовые рабочие ноды для LinuxCNC
        _nodes.Add(new MotionNode { CanvasX = 50, CanvasY = 100 });
        _nodes.Add(new StepgenNode { CanvasX = 450, CanvasY = 150 });
    }

    protected override void OnPointerPressed(PointerPressedEventArgs e)
    {
        base.OnPointerPressed(e);
        var pos = e.GetPosition(this);

        // Проверяем, кликнул ли пользователь по какой-либо ноде (размер блока 260x140)
        foreach (var node in _nodes)
        {
            var rect = new Rect(node.CanvasX, node.CanvasY, 260, 140);
            if (rect.Contains(pos))
            {
                _draggedNode = node;
                _pointerOffset = new Point(pos.X - node.CanvasX, pos.Y - node.CanvasY);
                e.Handled = true;
                break;
               
                ////files

            }
        }
    }

    protected override void OnPointerMoved(PointerEventArgs e)
    {
        base.OnPointerMoved(e);
        if (_draggedNode != null)
        {
            var pos = e.GetPosition(this);
            // Обновляем координаты ноды на холсте с учетом смещения мыши
            _draggedNode.CanvasX = pos.X - _pointerOffset.X;
            _draggedNode.CanvasY = pos.Y - _pointerOffset.Y;

            // Принудительно перерисовываем холст
            InvalidateVisual();
        }
    }

    protected override void OnPointerReleased(PointerReleasedEventArgs e)
    {
        base.OnPointerReleased(e);
        _draggedNode = null;
    }

    protected override void OnKeyDown(KeyEventArgs e)
    {
        base.OnKeyDown(e);

        // По нажатию на клавишу 'S' (Save) генерируем рабочий HAL файл
        if (e.Key == Key.S)
        {
            var sb = new System.Text.StringBuilder();
            sb.AppendLine("# ==========================================================");
            sb.AppendLine("# Generated by LinuxCNC Studio Node Engine (.NET 10)");
            sb.AppendLine("# ==========================================================");
            sb.AppendLine();
            sb.AppendLine("loadrt trivkins");
            sb.AppendLine("loadrt motmod servo_period_nsec=1000000 num_joints=3");
            sb.AppendLine("loadrt stepgen step_type=0,0,0");
            sb.AppendLine();
            sb.AppendLine("addf stepgen.make-pulses servo-thread");
            sb.AppendLine("addf motion-command-handler servo-thread");
            sb.AppendLine("addf motion-controller servo-thread");
            sb.AppendLine("addf stepgen.update-freq servo-thread");
            sb.AppendLine();
            sb.AppendLine("# Сигналы траекторий осей, скомпилированные из связей нод:");
            sb.AppendLine("net x-pos-cmd <= axis.0.motor-pos-cmd");
            sb.AppendLine("net x-pos-cmd => stepgen.0.position-cmd");

            string desktopPath = Environment.GetFolderPath(Environment.SpecialFolder.Desktop);
            string halFilePath = Path.Combine(desktopPath, "my_machine.hal");

            File.WriteAllText(halFilePath, sb.ToString(), System.Text.Encoding.UTF8);

            // Визуально мигнем фоном или выведем лог в консоль
            Console.WriteLine($"[КОНФИГУРАЦИЯ СКОМПИЛИРОВАНА] Файл сохранен на рабочий стол: {halFilePath}");
        }
    }


    public override void Render(DrawingContext context)
    {
        base.Render(context);

        var nodeBackground = new SolidColorBrush(Color.Parse("#2D2D2D")); // Темный индустриальный фон блока
        var nodeBorderPen = new Pen(Brushes.LightGray, 2);
        var wirePen = new Pen(Brushes.Gold, 3); // Золотые провода связей сигналов
        var pinBrush = Brushes.LimeGreen; // Зеленые точки клемм HAL

        // 1. Отрисовка динамической связи между выходами Motion и входами Stepgen
        // Координаты автоматически привязываются к текущему положению нод на холсте
        Point outPinPdf = new Point(_nodes[0].CanvasX + 260, _nodes[0].CanvasY + 50);
        Point inPinStep = new Point(_nodes[1].CanvasX, _nodes[1].CanvasY + 50);
        context.DrawLine(wirePen, outPinPdf, inPinStep);

        // 2. Отрисовка нод и их пинов
        foreach (var node in _nodes)
        {
            // Рисуем тело ноды
            var rect = new Rect(node.CanvasX, node.CanvasY, 260, 140);
            context.DrawRectangle(nodeBackground, nodeBorderPen, rect);

            // Отрисовка заголовка ноды
            var titleText = new FormattedText(
                node.Title,
                System.Globalization.CultureInfo.InvariantCulture,
                FlowDirection.LeftToRight,
                new Typeface("Segoe UI", FontStyle.Normal, FontWeight.Bold),
                13,
                Brushes.White
            );
            context.DrawText(titleText, new Point(node.CanvasX + 10, node.CanvasY + 10));

            // Отрисовка выходных пинов (справа)
            double outY = node.CanvasY + 50;
            foreach (var outPin in node.Outputs)
            {
                context.DrawEllipse(pinBrush, null, new Point(node.CanvasX + 260, outY), 5, 5);
                var pinText = new FormattedText(outPin.Name, System.Globalization.CultureInfo.InvariantCulture,
                    FlowDirection.LeftToRight, new Typeface("Consolas"), 10, Brushes.LightGray);
                context.DrawText(pinText, new Point(node.CanvasX + 260 - pinText.Width - 10, outY - 6));
                outY += 25;
            }

            // Отрисовка входных пинов (слева)
            double inY = node.CanvasY + 50;
            foreach (var inPin in node.Inputs)
            {
                context.DrawEllipse(pinBrush, null, new Point(node.CanvasX, inY), 5, 5);
                var pinText = new FormattedText(inPin.Name, System.Globalization.CultureInfo.InvariantCulture,
                    FlowDirection.LeftToRight, new Typeface("Consolas"), 10, Brushes.LightGray);
                context.DrawText(pinText, new Point(node.CanvasX + 10, inY - 6));
                inY += 25;
            }
        }
    }
}

public class NodeCanvasView : UserControl
{
    public NodeCanvasView()
    {
        var mainCanvas = new Canvas
        {
            Background = new SolidColorBrush(Color.Parse("#1E1E1E")) // Глубокий серый цвет холста редактора
        };

        var visualLayer = new HalVisualCanvas();
        visualLayer.Width = 3000;
        visualLayer.Height = 3000;

        mainCanvas.Children.Add(visualLayer);
        Content = mainCanvas;
    }
}
